'use strict';
const assert = require('assert');
const core = require('../src/mvu2shujuku');
module.exports = async function layoutPlanningHost(h) {
    const { page, runtimeTest, setStorageMode, assertStorageMode, openState, waitCommittedGold, record } = h;
    await setStorageMode(page, 'sqlite');
    const source = require('./layout-planning-card')(), result = core.convert(source);
    const state = await runtimeTest(page, source, core, 'layout-planning');
    await assertStorageMode(page, 'sqlite', '精细布局真实SQLite');
    const read = () => page.evaluate(() => JSON.parse(JSON.stringify(window.Mvu.getMvuData().stat_data)));
    const initial = core.parseInitVar(source.data.character_book.entries[0].content), current = await read();
    assert.deepStrictEqual(current.平台, initial.平台); assert.deepStrictEqual(current.角色, initial.角色);
    const roles = result.schema.find(g => g.name === '角色'), dictionary = roles.columns.find(c => c.zh === '字典');
    const key = roles.columns.find(c => c.zh === roles.keyCol);
    const comments = result.schema.find(g => JSON.stringify(g.writePaths) === JSON.stringify([['平台', '乙', '评论']]));
    assert.equal(roles.kind, 'rows'); assert(dictionary.isObject); assert(comments);
    const commentKey = comments.columns.find(c => c.zh === comments.keyCol), description = comments.columns.find(c => c.zh === comments.scalarValueCol);
    const sql = async text => {
        const response = await page.evaluate(async text => window.AutoCardUpdaterAPI.executeSqlMutation(text), text);
        assert(response && response.success !== false && !response.errors?.length, JSON.stringify(response));
    };
    await sql(`UPDATE "${comments.ident}" SET "${description.ident}"='只改乙' WHERE "${commentKey.ident}"='同名'`);
    await page.waitForFunction(() => window.Mvu.getMvuData().stat_data.平台?.乙?.评论?.同名 === '只改乙');
    current.平台.乙.评论.同名 = '只改乙'; assert.deepStrictEqual((await read()).平台, current.平台);
    await sql(`DELETE FROM "${comments.ident}" WHERE "${commentKey.ident}"='同名'`);
    await page.waitForFunction(() => Object.keys(window.Mvu.getMvuData().stat_data.平台?.乙?.评论 || {}).length === 0);
    current.平台.乙.评论 = {}; assert.deepStrictEqual((await read()).平台, current.平台);
    await sql(`UPDATE "${roles.ident}" SET "${dictionary.ident}"=json_set("${dictionary.ident}",'$."同键"."数量"',3.75) WHERE "${key.ident}"='甲'`);
    await page.waitForFunction(() => window.Mvu.getMvuData().stat_data.角色?.甲?.字典?.同键?.数量 === 3.75);
    current.角色.甲.字典.同键.数量 = 3.75; assert.deepStrictEqual((await read()).角色, current.角色, '局部SQL保留隐藏值与其他记录');
    await sql(`DELETE FROM "${roles.ident}" WHERE "${key.ident}"='甲'`);
    await page.waitForFunction(() => !window.Mvu.getMvuData().stat_data.角色?.甲);
    delete current.角色.甲; assert.deepStrictEqual((await read()).角色, current.角色, '记录删除不残留关联数据');
    const next = structuredClone(current); next.平台.甲.评论 = { 新键: '替换字典' }; next.平台.甲.额外 = { 计数: 2 };
    next.角色.乙.属性.数值 = 4.25; next.角色.乙.属性.复杂 = { 数量: 2.5 };
    const replace = async stat => assert.strictEqual(await page.evaluate(async stat => window.Mvu.replaceMvuData({ stat_data: stat }), stat), true);
    await replace(next); assert.deepStrictEqual(await read(), next);
    const rejected = structuredClone(next); delete rejected.角色;
    const before = await page.evaluate(() => JSON.stringify(window.AutoCardUpdaterAPI.exportTableAsJson()));
    assert.equal(await page.evaluate(async stat => window.Mvu.replaceMvuData({ stat_data: stat }), rejected), false);
    assert.deepStrictEqual(await read(), next);
    assert.equal(await page.evaluate(() => JSON.stringify(window.AutoCardUpdaterAPI.exportTableAsJson())), before, '拒绝替换前不调用宿主写入');
    const empty = { ...next, 角色: {} }; await replace(empty); assert.deepStrictEqual(await read(), empty, '必填字典允许清空记录');
    delete empty.可选; await replace(empty); assert.deepStrictEqual(await read(), empty, '可选容器缺失保留为缺失');
    await page.reload({ waitUntil: 'domcontentloaded' }); await openState(page, state); await waitCommittedGold(page, 37);
    assert.deepStrictEqual(await read(), empty, '刷新不补回可选容器');
    await replace({ ...empty, 可选: null }); assert.equal((await read()).可选, null);
    await replace({ ...empty, 可选: {} }); assert.deepStrictEqual((await read()).可选, {});
    await replace(initial); assert.deepStrictEqual(await read(), initial, '完整快照恢复并删除后加的扩展字段');
    await page.reload({ waitUntil: 'domcontentloaded' }); await openState(page, state); await waitCommittedGold(page, initial.状态.金币);
    assert.deepStrictEqual(await read(), initial, '精细布局保存后无损恢复');
    record('layout-planning-sqlite', { independentDictionaries: true, modelSql: true, scriptWrite: true, hiddenOwnership: true,
        rejectUnrepresentable: true, optionalMissingNullEmpty: true, decimals: true, snapshotRestore: true, reload: true });
};
