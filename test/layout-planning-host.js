'use strict';
const assert=require('assert');
const core=require('../src/mvu2shujuku');
module.exports=async function layoutPlanningHost(h){
    const {page,runtimeTest,setStorageMode,assertStorageMode,openState,waitCommittedGold,record}=h;
    await setStorageMode(page,'sqlite');
    const source=require('./layout-planning-card')(),result=core.convert(source);
    const state=await runtimeTest(page,source,core,'layout-planning');
    await assertStorageMode(page,'sqlite','布局规划真实SQLite');
    const read=()=>page.evaluate(()=>JSON.parse(JSON.stringify(window.Mvu.getMvuData().stat_data)));
    const initial=core.parseInitVar(source.data.character_book.entries[0].content),current=await read();
    assert.deepStrictEqual(current.平台,initial.平台);assert.deepStrictEqual(current.角色,initial.角色);
    const column=name=>{const g=result.schema.find(g=>g.name===name);assert(g.valueCol);return {g,c:g.columns.find(c=>c.zh===g.valueCol)};};
    const platforms=column('平台'),roles=column('角色');
    const sql=async text=>{const response=await page.evaluate(async text=>window.AutoCardUpdaterAPI.executeSqlMutation(text),text);assert(response&&response.success!==false,JSON.stringify(response));};
    const change=(owner,expression)=>sql('UPDATE "'+owner.g.ident+'" SET "'+owner.c.ident+'"='+expression+' WHERE row_id=1');
    const pc='"'+platforms.c.ident+'"',rc='"'+roles.c.ident+'"';
    await change(platforms,`json_replace(${pc},'$."乙"."评论"."同名"','只改乙')`);
    await page.waitForFunction(()=>window.Mvu.getMvuData().stat_data.平台?.乙?.评论?.同名==='只改乙');
    current.平台.乙.评论.同名='只改乙';assert.deepStrictEqual((await read()).平台,current.平台);
    await change(platforms,`json_remove(${pc},'$."乙"."评论"."同名"')`);
    await page.waitForFunction(()=>Object.keys(window.Mvu.getMvuData().stat_data.平台?.乙?.评论||{}).length===0);
    current.平台.乙.评论={};assert.deepStrictEqual((await read()).平台,current.平台);
    await change(roles,`json_set(${rc},'$."甲"."字典"."同键"."数量"',3.75)`);
    await page.waitForFunction(()=>window.Mvu.getMvuData().stat_data.角色?.甲?.字典?.同键?.数量===3.75);
    current.角色.甲.字典.同键.数量=3.75;assert.deepStrictEqual((await read()).角色,current.角色,'SQL保留隐藏值和其他同名记录');
    await change(roles,`json_remove(${rc},'$."甲"')`);
    await page.waitForFunction(()=>!window.Mvu.getMvuData().stat_data.角色?.甲);
    delete current.角色.甲;assert.deepStrictEqual((await read()).角色,current.角色);
    const next=structuredClone(current);next.平台.甲.评论={新键:'替换字典'};next.平台.甲.额外={计数:2};
    next.角色.乙.属性.数值=4.25;next.角色.乙.属性.复杂={数量:2.5};
    const replace=async stat=>assert.strictEqual(await page.evaluate(async stat=>window.Mvu.replaceMvuData({stat_data:stat}),stat),true);
    await replace(next);await page.waitForFunction(()=>window.Mvu.getMvuData().stat_data.角色?.乙?.属性?.数值===4.25);
    assert.deepStrictEqual(await read(),next);
    const absent=structuredClone(next);delete absent.角色;await replace(absent);
    await page.waitForFunction(()=>!Object.hasOwn(window.Mvu.getMvuData().stat_data,'角色'));
    assert.deepStrictEqual(await read(),absent,'脚本完整替换省略根变量保持缺失');
    await page.reload({waitUntil:'domcontentloaded'});await openState(page,state);await waitCommittedGold(page,37);
    assert.deepStrictEqual(await read(),absent,'刷新不能把缺失补成空对象');
    const empty={...absent,角色:{}};await replace(empty);
    assert.deepStrictEqual(await read(),empty,'显式空对象区别于缺失');
    await sql(`UPDATE "${roles.g.ident}" SET "${roles.c.ident}"=json_set("${roles.c.ident}",'$."临时"',json('{"姓名":"临时","属性":{"数值":1,"复杂":null},"数组":[],"字典":{}}')) WHERE row_id=1; UPDATE "${roles.g.ident}" SET "${roles.c.ident}"=json_remove("${roles.c.ident}",'$."临时"') WHERE row_id=1;`);
    assert.deepStrictEqual(await read(),empty,'同一SQL事务新增再清空仍是存在的空对象');
    await replace(next);await page.reload({waitUntil:'domcontentloaded'});await openState(page,state);await waitCommittedGold(page,37);
    assert.deepStrictEqual(await read(),next,'恢复完整快照后保存与刷新无损');
    record('layout-planning-sqlite',{independentDictionaries:true,modelSql:true,scriptWrite:true,hiddenOwnership:true,missingAndEmpty:true,netZeroSql:true,reload:true});
};
